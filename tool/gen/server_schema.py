#!/usr/bin/env python3
"""Generates Rubric's zonai server tables and rules (server/lib/src/**).

One spec below is the source of truth for the synced tables' SERVER shape.
Every table gets the zonai_sync columns (owner_id, rev, created_at, NON-null
updated_at, deleted_at) and owner-only rules. Re-run after editing TABLES;
the output is committed and formatted by `dart format`.
"""
import os, re

ROOT = os.path.join(os.path.dirname(__file__), '..', '..', 'server', 'lib', 'src')

# name: [(column, kind, nullable)]  kinds: text, int, real, bool
TABLES = {
    'rubrics': [('title', 'text', False), ('subject', 'text', False),
                ('is_template', 'bool', False), ('archived', 'bool', False),
                ('document', 'text', False), ('created_on', 'int', False)],
    'courses': [('name', 'text', False), ('section', 'text', False),
                ('term', 'text', False), ('archived', 'bool', False),
                ('created_on', 'int', False)],
    'students': [('course_id', 'text', False), ('first_name', 'text', False),
                 ('last_name', 'text', False), ('student_number', 'text', False),
                 ('email', 'text', False), ('notes', 'text', False),
                 ('archived', 'bool', False)],
    'assignments': [('course_id', 'text', False), ('title', 'text', False),
                    ('description', 'text', False), ('rubric_document', 'text', False),
                    ('source_rubric_id', 'text', True), ('due_on', 'int', True),
                    ('points_possible', 'real', False), ('closed', 'bool', False),
                    ('created_on', 'int', False)],
    'evaluations': [('assignment_id', 'text', False), ('student_id', 'text', False),
                    ('status', 'text', False), ('document', 'text', False),
                    ('updated_on', 'int', False)],
    'comment_snippets': [('body', 'text', False), ('category', 'text', False),
                         ('use_count', 'int', False)],
}

DART = {'text': 'String', 'int': 'int', 'real': 'double', 'bool': 'bool'}
BUILDER = {'text': 'text', 'int': 'integer', 'real': 'real', 'bool': 'boolean'}

def camel(s):
    parts = s.split('_')
    return parts[0] + ''.join(p.title() for p in parts[1:])

def pascal(s):
    return ''.join(p.title() for p in s.split('_'))

def singular(s):
    return s[:-1] if s.endswith('s') else s

HEADER = '// GENERATED by tool/gen/server_schema.py -- edit the spec there, not this file.\n'

def schema(table, cols):
    row = pascal(singular(table))
    tcls = row + 'Table'
    idcls = pascal(table) + 'Id'
    all_cols = [('owner_id', 'text', False)] + cols + [('rev', 'int', False)]
    fields = '\n'.join(
        f'  final {DART[k]}{"?" if n else ""} {camel(c)};' for c, k, n in all_cols)
    ctor = '\n'.join(
        f'    {"required " if not n else ""}this.{camel(c)},' for c, k, n in all_cols)
    inits = ',\n'.join(
        f"      {camel(c)} = $.{BUILDER[k]}('{c}', (s) => s.{camel(c)})" for c, k, n in all_cols)
    reads = '\n'.join(f'    {camel(c)}: read({camel(c)}),' for c, k, n in all_cols)
    colfields = '\n'.join(
        f'  final ColumnType<{DART[k]}{"?" if n else ""}> {camel(c)};' for c, k, n in all_cols)
    return f'''{HEADER}import 'package:rubric_server/src/ids.dart';
import 'package:zonai_schema/zonai_schema.dart';

final class {row} {{
  {row}({{
    required this.id,
{ctor}
    required this.createdAt,
    required this.updatedAt,
    this.deletedAt,
  }});

  final {idcls} id;
{fields}
  final DateTime createdAt;
  final DateTime updatedAt;
  final DateTime? deletedAt;
}}

/// Synced with zonai_sync: owner-scoped, revisioned, tombstoned, and a
/// NON-null updated_at so zonai stamps it on insert (sync cursors need it).
final class {tcls} extends Table<{row}> {{
  {tcls}(super.$)
    : id = $.id(
        'id',
        (s) => s.id,
        fromString: {idcls}.new,
        generate: {idcls}.generate,
      ),
{inits},
      createdAt = $.createdAt('created_at', (s) => s.createdAt),
      updatedAt = $.updatedAt('updated_at', (s) => s.updatedAt),
      deletedAt = $.dateTime('deleted_at', (s) => s.deletedAt);

  @override
  {row} fromRow(RowReader read) => {row}(
    id: read(id),
{reads}
    createdAt: read(createdAt),
    updatedAt: read(updatedAt),
    deletedAt: read(deletedAt),
  );

  final IdColumn<{idcls}> id;
{colfields}
  final DateTimeColumn createdAt;
  final DateTimeColumn updatedAt;
  final ColumnType<DateTime?> deletedAt;
}}

final {camel(table)} = table('{table}', {tcls}.new);
'''

def rules(table):
    row = pascal(singular(table)); tcls = row + 'Table'
    return (f'''{HEADER}import 'package:rubric_server/src/schemas/{table}.dart';
import 'package:zonai_schema/zonai_schema.dart';

{row}TableRules main() => {row}TableRules();

/// Signed-in users may ask; the row rules decide. canUpdate must be allowed
/// here: zonai checks table rules BEFORE looking the row up.
final class {row}TableRules extends TableRules<{tcls}, {row}> {{
  {row}TableRules() : super({camel(table)});

  @override
  Future<bool> canView(Jwt? jwt) async => jwt != null;

  @override
  Future<bool> canList(Jwt? jwt) async => jwt != null;

  @override
  Future<bool> canCreate(Jwt? jwt) async => jwt != null;

  @override
  Future<bool> canUpdate(Jwt? jwt) async => jwt != null;

  @override
  Future<bool> canDelete(Jwt? jwt) async => false;
}}
''', f'''{HEADER}import 'package:rubric_server/src/schemas/{table}.dart';
import 'package:zonai_schema/zonai_schema.dart';

{row}RowRules main() => {row}RowRules();

/// A teacher sees and changes only their own rows. Ownership is checked on
/// both sides of an update so a row can't be handed to someone else; hard
/// deletes are refused (sync deletes are tombstones).
final class {row}RowRules extends RowRules<{tcls}, {row}> {{
  {row}RowRules() : super({camel(table)});

  bool _owns(Jwt? jwt, {row} row) =>
      jwt != null && jwt.userId.value == row.ownerId;

  /// Reads are narrowed to the caller's rows (zonai #45): an unscoped list
  /// returns "your rows" instead of a 403, and counts take the plain-COUNT
  /// path while still counting only what the caller may see. canView still
  /// runs on every row in scope.
  @override
  Future<Where?> viewScope(Jwt? jwt) async =>
      jwt == null ? null : Eq('owner_id', jwt.userId.value);

  @override
  Future<bool> canView(Jwt? jwt, {row} row) async => _owns(jwt, row);

  @override
  Future<bool> canCreate(Jwt? jwt, {row} row) async => _owns(jwt, row);

  @override
  Future<bool> canUpdate(Jwt? jwt, {row} before, {row} after) async =>
      _owns(jwt, before) && _owns(jwt, after);

  @override
  Future<bool> canDelete(Jwt? jwt, {row} row) async => false;
}}
''')

def ids():
    out = [HEADER + "import 'package:zonai_schema/zonai_schema.dart' as z;\n"]
    for t in ['users', *TABLES]:
        c = pascal(t) + 'Id'
        out.append(f'''
/// Any string is accepted: ids are chosen by clients (created offline).
final class {c} implements z.Id {{
  const {c}(this.value);

  factory {c}.generate() =>
      {c}('${{DateTime.now().microsecondsSinceEpoch}}_{t[:4]}');

  @override
  final String value;

  @override
  String toString() => value;

  String toJson() => value;
}}
''')
    return ''.join(out)

def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, 'w') as f:
        f.write(text)

write('ids.dart', ids())
for t, cols in TABLES.items():
    write(f'schemas/{t}.dart', schema(t, cols))
    tr, rr = rules(t)
    write(f'rules/{singular(t)}_table_rules.dart', tr)
    write(f'rules/{singular(t)}_row_rules.dart', rr)
print('generated', len(TABLES), 'tables')
